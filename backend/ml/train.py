"""Train local demo models only from generated synthetic data."""
from __future__ import annotations

import csv
from pathlib import Path

import joblib
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import cross_val_predict, cross_val_score
from sklearn.multioutput import MultiOutputClassifier

from .generate import DATA_PATH, RISK_LEVELS, SUPPORTS, build

ROOT = Path(__file__).resolve().parent
ARTIFACTS = ROOT / "artifacts"
# has_message tells the forests whether text_risk means anything for this row; it must stay
# second-to-last, with text_risk last, because predict.py assembles the row in this order.
FEATURES = ["mood", "sleep", "safety", "anxiety", "case_pressure", "missed_checkins", "engagement",
            "has_message", "text_risk"]

# scikit-learn's default token_pattern (r"(?u)\b\w\w+\b") relies on \b word-boundaries, which do not
# align correctly after Devanagari dependent vowel signs (matras) — the same issue found and fixed in
# chatbot.py's safety regex. Left at the default, it mangles almost every Hindi word into a garbage
# fragment (e.g. "सुरक्षित" -> "रक"), producing a useless model for Hindi text. This matches runs of
# non-whitespace, non-punctuation characters directly (works for English, Hindi and Hinglish alike),
# expressed as a plain string rather than a custom preprocessor/tokenizer callable — a pickled function
# object breaks the moment it's unpickled from a different __main__ module (exactly what happens here,
# since this codebase runs train.py and predict.py as separate `python -m` entry points).
TOKEN_PATTERN = r"(?u)[^\s!\"#$%&'()*+,\-./:;<=>?@\[\\\]^_`{|}~।॥]+"


def train() -> Path:
    if not DATA_PATH.exists(): build()
    with DATA_PATH.open(encoding="utf-8") as handle: rows = list(csv.DictReader(handle))
    # A CSV generated by an older version of generate.py is missing the columns this trainer
    # expects, and reusing it fails with a bare KeyError. Regenerate instead of asking the user
    # to know that deleting ml/data/ is the fix.
    required = {"text", "risk_band", "score", "escalates", "has_message", *FEATURES[:-2]}
    if not rows or not required.issubset(rows[0]):
        build()
        with DATA_PATH.open(encoding="utf-8") as handle: rows = list(csv.DictReader(handle))
    text = [row["text"] for row in rows]
    vectorizer = TfidfVectorizer(ngram_range=(1, 2), min_df=1, sublinear_tf=True, token_pattern=TOKEN_PATTERN)
    matrix = vectorizer.fit_transform(text)
    bands = [row["risk_band"] for row in rows]
    text_model = LogisticRegression(max_iter=1000, random_state=42).fit(matrix, bands)
    # The text_risk feature fed to the downstream forests must be an OUT-OF-FOLD prediction.
    # Using text_model.predict(matrix) here meant every row's feature came from a model that
    # had already seen that row's label, so the forests learned from a cleaner text signal
    # than they will ever get at inference time.
    out_of_fold = cross_val_predict(LogisticRegression(max_iter=1000, random_state=42), matrix, bands, cv=5)
    text_risk = [RISK_LEVELS.index(value) for value in out_of_fold]
    x = [[float(row[name]) for name in FEATURES[:-2]]
         + [float(row["has_message"]), text_risk[index] if int(row["has_message"]) else 0]
         for index, row in enumerate(rows)]
    scores = [float(row["score"]) for row in rows]
    score_model = RandomForestRegressor(n_estimators=140, random_state=42, min_samples_leaf=2).fit(x, scores)
    escalates = [int(row["escalates"]) for row in rows]
    escalation_model = RandomForestClassifier(n_estimators=140, random_state=42, min_samples_leaf=2).fit(x, escalates)
    targets = [[int(name in row["interventions"].split("|")) for name in SUPPORTS] for row in rows]
    intervention_model = MultiOutputClassifier(RandomForestClassifier(n_estimators=100, random_state=42, min_samples_leaf=2)).fit(x, targets)
    ARTIFACTS.mkdir(exist_ok=True)
    joblib.dump({"vectorizer": vectorizer, "text": text_model, "score": score_model, "escalation": escalation_model,
                 "intervention": intervention_model, "metrics": evaluate(matrix, bands, x, scores, escalates)},
                ARTIFACTS / "distress_models.joblib")
    return ARTIFACTS / "distress_models.joblib"


def evaluate(matrix, bands, x, scores, escalates) -> dict:
    """Cross-validated scores stored alongside the models, so the artifact carries honest
    numbers rather than accuracy claimed from the training set. These describe performance on
    SYNTHETIC data and say nothing about real-world clinical accuracy."""
    return {
        "text_band_accuracy": round(float(cross_val_score(
            LogisticRegression(max_iter=1000, random_state=42), matrix, bands, cv=5).mean()), 3),
        "score_r2": round(float(cross_val_score(
            RandomForestRegressor(n_estimators=140, random_state=42, min_samples_leaf=2), x, scores, cv=5).mean()), 3),
        "escalation_accuracy": round(float(cross_val_score(
            RandomForestClassifier(n_estimators=140, random_state=42, min_samples_leaf=2), x, escalates, cv=5).mean()), 3),
        "rows": len(scores),
        "note": "5-fold cross-validation on synthetic data; not a clinical accuracy claim.",
    }


if __name__ == "__main__":
    path = train(); assert path.exists(); print(path)
